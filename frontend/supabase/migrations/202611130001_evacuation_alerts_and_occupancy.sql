create table if not exists public.evacuation_alerts (
  id bigint generated by default as identity primary key,
  reason text not null check (char_length(reason) <= 500),
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  created_at timestamptz not null default now(),
  acknowledged_at timestamptz
);
alter table public.evacuation_alerts enable row level security;
drop policy if exists "Residents can report evacuation alerts" on public.evacuation_alerts;
create policy "Residents can report evacuation alerts" on public.evacuation_alerts for insert with check (true);
drop policy if exists "Signed-in officials can view evacuation alerts" on public.evacuation_alerts;
create policy "Signed-in officials can view evacuation alerts" on public.evacuation_alerts for select to authenticated using (true);

-- Confirmed evacuee assignments are the occupancy ledger. The RPC takes a row
-- lock on the destination center before checking/incrementing its capacity.
create table if not exists public.shelter_occupancy (
  resident_key text primary key,
  shelter_id bigint not null references public.shelter(shelter_id) on delete cascade,
  assigned_at timestamptz not null default now(),
  check (char_length(resident_key) between 16 and 128)
);

create or replace function public.assign_resident_to_shelter(p_resident_key text, p_shelter_id bigint)
returns boolean language plpgsql security definer set search_path = public as $$
declare
  current_assignment bigint;
  current_count integer;
  max_count integer;
begin
  if p_resident_key is null or char_length(p_resident_key) not between 16 and 128 then
    raise exception 'Invalid resident key';
  end if;
  select shelter_id into current_assignment from public.shelter_occupancy
    where resident_key = p_resident_key for update;
  if current_assignment = p_shelter_id then return true; end if;
  select curr_capacity, max_capacity into current_count, max_count
    from public.shelter where shelter_id = p_shelter_id for update;
  if not found or current_count >= max_count then return false; end if;
  if current_assignment is not null then
    update public.shelter set curr_capacity = greatest(0, curr_capacity - 1) where shelter_id = current_assignment;
  end if;
  insert into public.shelter_occupancy(resident_key, shelter_id)
    values (p_resident_key, p_shelter_id)
    on conflict (resident_key) do update set shelter_id = excluded.shelter_id, assigned_at = now();
  update public.shelter set curr_capacity = curr_capacity + 1 where shelter_id = p_shelter_id;
  return true;
end;
$$;

revoke all on function public.assign_resident_to_shelter(text, bigint) from public, anon, authenticated;
grant execute on function public.assign_resident_to_shelter(text, bigint) to service_role;
